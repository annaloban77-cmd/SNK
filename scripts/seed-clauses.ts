async function main() {
  console.log('📜 seed-clauses — добавление ключевых пунктов ГОСТ (StandardClause)')
  let totalInserted = 0
  let standardsUpdated = 0

  for (const seed of STANDARD_CLAUSES) {
    const standard = await db.standard.findFirst({
      where: { code: { startsWith: seed.codePrefix } },
      select: { id: true, code: true },
    })
    if (!standard) {
      console.log(`  ✗ Стандарт не найден: ${seed.codePrefix}`)
      continue
    }
    // Delete existing clauses for this standard (idempotent)
    await db.standardClause.deleteMany({ where: { standardId: standard.id } })
    // Insert new clauses
    for (const clause of seed.clauses) {
      await db.standardClause.create({
        data: {
          standardId: standard.id,
          number: clause.number,
          title: clause.title,
          text: clause.text,
          severity: clause.severity,
        },
      })
      totalInserted++
    }
    standardsUpdated++
    console.log(`  ✓ ${standard.code}: ${seed.clauses.length} пунктов`)
  }

  console.log(`\n✅ seed-clauses завершён: добавлено ${totalInserted} пунктов в ${standardsUpdated} стандартов`)
}

main()
  .catch((e) => {
    console.error('❌ seed-clauses failed:', e)
    process.exit(1)
  })
  .finally(async () => {
    await db.$disconnect()
  })
